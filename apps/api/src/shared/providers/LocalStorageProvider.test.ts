import { expect, test } from 'bun:test'

import { LocalStorageProvider } from './LocalStorageProvider'
import { isValidStorageKey, normalizeFileExtension, resolveUploadPath } from './storageKey'

const VALID_KEY = '3f2b8c1e-9a4d-4c7b-8e2f-1a2b3c4d5e6f.png'
const VALID_THUMB_KEY = '3f2b8c1e-9a4d-4c7b-8e2f-1a2b3c4d5e6f_thumb.png'
const TRAVERSAL_KEYS = [
  '....//....//proc/self/environ',
  '../../proc/self/environ',
  '..%2F..%2Fetc%2Fpasswd',
  '/etc/passwd',
  `${VALID_KEY}/../../../etc/passwd`,
  'sub/dir/file.png',
  '',
]

test('accepts the key formats generated by upload and thumbnail', () => {
  expect(isValidStorageKey(VALID_KEY)).toBe(true)
  expect(isValidStorageKey(VALID_THUMB_KEY)).toBe(true)
  expect(isValidStorageKey('3f2b8c1e-9a4d-4c7b-8e2f-1a2b3c4d5e6f.JPG')).toBe(true)
})

test('rejects traversal and non-generated keys', () => {
  for (const key of TRAVERSAL_KEYS) {
    expect(isValidStorageKey(key)).toBe(false)
    expect(() => resolveUploadPath(key)).toThrow()
  }
})

test('getFilePath returns undefined for traversal keys and stays inside the upload dir', () => {
  const storageProvider = new LocalStorageProvider()
  for (const key of TRAVERSAL_KEYS) {
    expect(storageProvider.getFilePath(key)).toBeUndefined()
  }
  expect(storageProvider.getFilePath(VALID_KEY)).toBe(`/tmp/uploads/${VALID_KEY}`)
})

test('upload refuses a traversal key', async () => {
  const storageProvider = new LocalStorageProvider()
  await expect(storageProvider.upload('../escape.txt', Buffer.from('x'), 'text/plain')).rejects.toThrow()
})

test('normalizeFileExtension keeps safe extensions and falls back to .bin', () => {
  expect(normalizeFileExtension('.JPG')).toBe('.jpg')
  expect(normalizeFileExtension('')).toBe('.bin')
  expect(normalizeFileExtension('.p n g')).toBe('.bin')
  expect(normalizeFileExtension('.verylongextension')).toBe('.bin')
})
